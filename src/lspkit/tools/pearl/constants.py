# 珍珠炮常量表：集中定义搜索范围、物理系数、模拟窗口与方向矩阵，供 core 下的求解、
# 递推与模拟复用；所有数值都沿用旧版 Tkinter 实现，改动会直接影响黄金快照。
from __future__ import annotations

# ------ 搜索范围与微调窗口（gt = 游戏刻） ------ #
# 当量搜索覆盖 1..MAX_TICKS 这些飞行时刻，再远的解旧版也不列出。
MAX_TICKS = 300
# 平射微调：在初解基础上每轴 ±2 内枚举，共 5**2 = 25 种组合。
FLAT_TUNING = range(-2, 3)
# 抛射微调：抛射对 Y 更敏感，放宽到每轴 ±10，共 21**2 = 441 种组合。
EJECT_TUNING = range(-10, 11)
# 抛射要求珍珠在选定 gt 到达的高度（方块，Y 轴），与旧界面标注一致。
EJECT_TARGET_Y = 128
# 抛射解的有效 Y 区间（闭区间）：只有落点 Y 落在 [128, 129] 内才保留。
EJECT_Y_WINDOW = (128, 129)

# ------ 物理系数：每 gt 的阻尼与重力 ------ #
# 水平速度每 gt 乘 0.99；累计位移 = 100 * v * (1 - 0.99**t)，t 大时约为 100 * v。
DAMPING = 0.99
# 每 gt 从 Y 速度减去的重力加速度（方块/gt）；终端速度 = -0.03 / (1 - 0.99) = -3。
GRAVITY = 0.03

# ------ 手动模拟参数 ------ #
# 手动模拟的落地高度（Y 坐标）；轨迹里第一次低于它就视为落地
GROUND_Y = 0.0
# simulate 动作的默认模拟时长（gt）：比当量搜索上限更长，便于看到落地时刻。
MAX_SIM_TICKS = 600

# ------ 方向 → 动量矩阵 ------ #
# 45° 旋转后的四象限 → 方向与动量矩阵
# 行是 X / Z 轴，列是蓝 / 红 TNT 数量，乘 (blue, red) 即得世界坐标下的单位动量。
# 只有 4 组 ±1：TNT 沿 45° 对角线摆放，旋转后每个象限的符号组合固定。
DIRECTION_MATRICES = {
    "east": [[1, 1], [-1, 1]],
    "west": [[-1, -1], [-1, 1]],
    "north": [[1, -1], [-1, -1]],
    "south": [[1, -1], [1, 1]],
}
